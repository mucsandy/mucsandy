#!/usr/bin/env python3
"""Build GitHub-safe HTML from actual SVG aspect ratios, using only stdlib."""

from __future__ import annotations

import argparse
from fractions import Fraction
import html
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from common import atomic_write

ROOT = Path(__file__).resolve().parents[1]


def aspect_ratio(path: Path) -> Fraction:
    root = ET.parse(path).getroot()
    if root.tag != "{http://www.w3.org/2000/svg}svg":
        raise ValueError(f"{path} is not an SVG document")
    values = root.get("viewBox", "").split()
    if len(values) != 4:
        raise ValueError(f"{path} needs a four-number viewBox")
    x, y, width, height = map(Fraction, values)
    if x != 0 or y != 0 or width <= 0 or height <= 0:
        raise ValueError(f"{path} needs a positive viewBox with a zero origin")
    return width / height


def panel_sizes(portrait: Path, card: Path, total_width: int = 850) -> tuple[int, int, int]:
    """Derive the shared height and each image width without fixed proportions.

    HTML dimensions are integers. We round the exact shared height and the
    first width; the second width is the remainder, so widths always total850.
    Setting the common height explicitly makes the two panels line up exactly.
    The resulting aspect-ratio distortion is less than one display pixel.
    """
    portrait_aspect = aspect_ratio(portrait)
    card_aspect = aspect_ratio(card)
    exact_height = Fraction(total_width, 1) / (portrait_aspect + card_aspect)
    portrait_width = round(exact_height * portrait_aspect)
    return portrait_width, total_width - portrait_width, round(exact_height)


def write_readme(
    config: Path = ROOT / "profile.json",
    portrait: Path = ROOT / "ascii-portrait.svg",
    card: Path = ROOT / "info-card.svg",
    heatmap: Path = ROOT / "contrib-heatmap.svg",
    output: Path = ROOT / "README.md",
) -> tuple[int, int, int]:
    profile = json.loads(config.read_text(encoding="utf-8"))
    username = profile["username"]
    if not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})", username):
        raise ValueError("Invalid GitHub username")
    portrait_width, card_width, height = panel_sizes(portrait, card)
    # README assets deliberately remain relative repo paths. Widths are derived
    # from the viewBoxes every time either local static artwork changes.
    try:
        asset_paths = [str(path.resolve().relative_to(output.parent.resolve())) for path in (heatmap, portrait, card)]
    except ValueError as error:
        raise ValueError("README assets must be inside the output README directory") from error
    heatmap_src, portrait_src, card_src = [html.escape(path, quote=True) for path in asset_paths]
    safe_username = html.escape(username, quote=True)
    details = []
    for entry in profile["rows"]:
        label = entry.get("label", "")
        value = " · ".join(entry["items"]) if "items" in entry else entry["value"]
        details.append(f"{label}: {value}" if label else value)
    card_alt = html.escape(f"{username}. " + "; ".join(details), quote=True)
    content = f'''<!-- Generated by scripts/render_readme.py. Edit profile.json, then render the card. -->
<div align="center">

<h3><code>{safe_username}@github ~ $ ./contributions.sh</code></h3>

<p align="center">
  <img src="{heatmap_src}" width="850" alt="{safe_username}'s contribution calendar, 53 weeks, with contribution statistics">
</p>

<br><br>

<h3><code>{safe_username}@github ~ $ whoami</code></h3>

<table align="center">
  <tr>
    <td valign="top" align="center">
      <img src="{portrait_src}" width="{portrait_width}" height="{height}" alt="Monochrome ASCII portrait of {safe_username}, typed row by row">
    </td>
    <td valign="top" align="center">
      <img src="{card_src}" width="{card_width}" height="{height}" alt="{card_alt}">
    </td>
  </tr>
</table>

<br>

<p>
  <sub>
    Built with Python · Self-contained SVGs · Daily contribution refresh
    <br>
    <a href="./scripts/">Source</a> ·
    <a href="./.github/workflows/refresh-heatmap.yml">Workflow</a> ·
    <a href="./SETUP.md">Setup</a>
  </sub>
</p>

</div>
'''
    atomic_write(output, content)
    print(f"Wrote {output}: portrait {portrait_width}px + card {card_width}px = 850px; shared height {height}px")
    return portrait_width, card_width, height


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "profile.json")
    parser.add_argument("--portrait", type=Path, default=ROOT / "ascii-portrait.svg")
    parser.add_argument("--card", type=Path, default=ROOT / "info-card.svg")
    parser.add_argument("--heatmap", type=Path, default=ROOT / "contrib-heatmap.svg")
    parser.add_argument("--output", type=Path, default=ROOT / "README.md")
    args = parser.parse_args()
    write_readme(args.config, args.portrait, args.card, args.heatmap, args.output)


if __name__ == "__main__":
    main()
